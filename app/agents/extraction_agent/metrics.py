"""
Metric catalogue + the shapes the LLM must answer in.

Core 12 metrics (what the user asked for) plus three supporting lines needed
by the checks and ratios (total_liabilities, current_assets, current_liabilities).

The model only COPIES numbers it sees. Anything that needs arithmetic
(total debt, ratios, growth) is done in code, never by the model.
"""

from __future__ import annotations

from typing import List, Optional

from pydantic import BaseModel, Field

# statement → {metric: what to look for}
PROFIT_LOSS = {
    "revenue": "Total revenue / revenue from operations / net sales (the top line).",
    "gross_profit": "Gross profit / gross margin, ONLY if the statement prints it. Otherwise null.",
    "operating_profit": "Operating profit / operating income / EBIT, ONLY if printed. Otherwise null.",
    "net_profit": "Net profit / profit for the year / net income attributable to the owners of the company (after tax).",
    "eps": "Basic earnings per share (per-share amount, not in crore/million).",
}
BALANCE_SHEET = {
    "total_assets": "Total assets.",
    "total_liabilities": "Total liabilities, ONLY if printed as one line. Otherwise null.",
    "total_equity": "Total equity / total shareholders' equity (include non-controlling interest if the total line includes it).",
    "current_assets": "Total current assets.",
    "current_liabilities": "Total current liabilities.",
    "cash": "Cash and cash equivalents (only that line; do not add investments).",
    "receivables": "Trade receivables / accounts receivable, net.",
}
CASH_FLOW = {
    "operating_cash_flow": "Net cash from / generated by operating activities.",
    "capex": "Purchase of / payments for property, plant and equipment (and intangible assets if on the same line). Report as the printed number.",
}

STATEMENTS = {
    "profit_loss": PROFIT_LOSS,
    "balance_sheet": BALANCE_SHEET,
    "cash_flow": CASH_FLOW,
}

# What the user sees, and the unit rule for each metric.
PER_SHARE = {"eps"}


class Item(BaseModel):
    metric: str = Field(description="One of the requested metric ids, exactly as given.")
    current: Optional[float] = Field(
        None, description="Value for the LATEST year column, exactly as printed. Negative if shown in brackets or with a minus. null if the line is absent."
    )
    prior: Optional[float] = Field(
        None, description="Value for the PREVIOUS year column, exactly as printed. null if absent."
    )
    page: Optional[int] = Field(None, description="The PDF page number (from the PAGE header) where you read it.")
    source_line: Optional[str] = Field(
        None, description="The line of text you copied the numbers from, verbatim, including the label."
    )


class DebtLine(BaseModel):
    label: str = Field(description="The line label as printed, e.g. 'Borrowings' or 'Term debt'.")
    current: Optional[float] = None
    prior: Optional[float] = None
    page: Optional[int] = None
    source_line: Optional[str] = None


class StatementAnswer(BaseModel):
    items: List[Item] = Field(default_factory=list)
    debt_lines: List[DebtLine] = Field(
        default_factory=list,
        description="Balance sheet only: every separate line that is interest-bearing debt (borrowings, term debt, commercial paper, debentures, bank loans), current AND non-current. Do NOT include lease liabilities, trade payables or provisions. Do NOT add them up.",
    )


SYSTEM_PROMPT = """You read one financial statement of a company's annual report and copy specific numbers out of it.

Rules:
- The text below is from a PDF. Pages start with a header like "=== PAGE 302 ===".
- Copy numbers EXACTLY as printed. Never calculate, add, convert units or estimate.
- The statement has a latest-year column and a previous-year column. 'current' = latest year, 'prior' = previous year. Ignore any "Note" reference column.
- Brackets or a minus sign mean a negative number.
- If a line is not in the text, return null for it. Do not guess.
- Prefer the CONSOLIDATED figures when both consolidated and standalone appear.
- For each value also return the PDF page it came from and the verbatim source line.
"""


def build_user_prompt(section: str, pages: list[dict]) -> str:
    wanted = STATEMENTS[section]
    lines = "\n".join(f'- "{k}": {v}' for k, v in wanted.items())
    unit = next((p["unit"] for p in pages if p.get("unit")), "") or "not stated"
    body = "\n\n".join(f"=== PAGE {p['pdf_page']} ===\n{p['text']}" for p in pages)
    extra = ""
    if section == "balance_sheet":
        extra = "\nAlso fill `debt_lines` as described."
    return (
        f"Statement type: {section.replace('_', ' ')}\n"
        f"Unit printed on the statement: {unit}\n\n"
        f"Return one item for each of these metric ids:\n{lines}{extra}\n\n"
        f"TEXT:\n{body}"
    )
